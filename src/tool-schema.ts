import { z } from "zod";

/**
 * Ловушка для полей, которых у инструмента нет. Через `catchall`, а не
 * `strict`: так в отказе остаётся имя поля — агенту важно узнать не только
 * что он выдумал поле, но и какое именно.
 *
 * Проверка через `refine`, а не `z.never()`: `catchall(z.never())` в zod
 * означает «поведение по умолчанию», то есть лишние поля молча выбрасываются
 * — ровно то, чего мы не хотим.
 */
export const FORBIDDEN_FIELD = z.any().refine(() => false, {
  message:
    "Такого поля у инструмента нет. Названия, сроки, приоритеты, исполнителей, " +
    "роли и категории меняет человек, а не агент",
});
